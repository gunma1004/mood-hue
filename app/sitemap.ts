export default function sitemap(): MetadataRoute.Sitemap {
  const baseUrl = 'https://mood-hue.netlify.app';

  // 1. 메인 대표 홈 페이지
  const mainRoute: MetadataRoute.Sitemap = [
    {
      url: baseUrl,
      lastModified: new Date(),
      changeFrequency: 'daily',
      priority: 1.0,
    },
  ];

  // 2. 상단 카테고리 메인 페이지들
  const categoryRoutes: MetadataRoute.Sitemap = [
    'services',
    'prices',
    'travel',
    'places',
    'reviews',
  ].map((route) => ({
    url: `${baseUrl}/${route}`,
    lastModified: new Date(),
    changeFrequency: 'weekly',
    priority: 0.8,
  }));

  // 3. 메인 5개 제휴업체 상세 페이지 (/shop/1 ~ /shop/5)
  const shopRoutes: MetadataRoute.Sitemap = [1, 2, 3, 4, 5].map((id) => ({
    url: `${baseUrl}/shop/${id}`,
    lastModified: new Date(),
    changeFrequency: 'weekly',
    priority: 0.8,
  }));

  const directRegionRoutes: MetadataRoute.Sitemap = [];
  const spacedMassageRoutes: MetadataRoute.Sitemap = [];
  const dongQueryRoutes: MetadataRoute.Sitemap = [];

  // 4. 지역 데이터를 순회하며 구/시 단위 및 하위 동(쿼리스트링) 단위까지 모두 생성
  Object.keys(regionData).forEach((regionKey) => {
    const districts = regionData[regionKey].districts;
    
    Object.keys(districts).forEach((districtKey) => {
      const districtObj = districts[districtKey];
      const districtName = districtObj.name;
      const dongs = districtObj.dongs;

      // 구/시 단위 경로 (기본 + 띄어쓰기 회피형)
      const directUrl = `${baseUrl}/${regionKey}/${encodeURIComponent(districtName)}`;
      const massageUrl = `${baseUrl}/massage/${regionKey}/${encodeURIComponent(districtName)}`;

      directRegionRoutes.push({
        url: directUrl,
        lastModified: new Date(),
        changeFrequency: 'daily',
        priority: 0.9,
      });

      spacedMassageRoutes.push({
        url: massageUrl,
        lastModified: new Date(),
        changeFrequency: 'daily',
        priority: 0.9,
      });

      // 🌟 각 구/시 하위에 속한 모든 동(dong)을 쿼리스트링(?dong=...) 형태로 추가
      dongs.forEach((dong) => {
        spacedMassageRoutes.push({
          url: `${massageUrl}?dong=${encodeURIComponent(dong)}`,
          lastModified: new Date(),
          changeFrequency: 'daily',
          priority: 0.85,
        });
      });
    });
  });

  return [
    ...mainRoute,
    ...categoryRoutes,
    ...shopRoutes,
    ...directRegionRoutes,
    ...spacedMassageRoutes,
  ];
}